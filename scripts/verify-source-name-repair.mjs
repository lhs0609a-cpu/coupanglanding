const eq = (input, expect) => {
  const got = stripRepeatedTail(input);
  const ok = got === expect;
  console.log(`${ok ? '✅' : '❌'} ${JSON.stringify(input).slice(0, 62)}\n     → ${JSON.stringify(got)}${ok ? '' : `  (기대: ${JSON.stringify(expect)})`}`);
  if (!ok) failed++;
};

