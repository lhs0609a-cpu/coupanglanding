function hashSeed(s) {
  let h = 2166136261;
  for (const ch of String(s || 'default')) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return Math.abs(h);
}
export function pickPersona(seed) { return PERSONAS[hashSeed(seed) % PERSONAS.length]; }

