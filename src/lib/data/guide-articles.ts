/**
 * 공개 가이드 아티클 (검색 유입용 + 실제 셀러에게 쓸모 있는 문서)
 *
 * 글 하나 = 이 배열의 항목 하나. 페이지 파일을 새로 만들지 않고 여기에 추가하면
 * /guide/{slug} 로 발행되고 sitemap 에도 자동 등록된다.
 *
 * ── 원칙 ──
 * 1) 숨김 텍스트·키워드 스터핑 금지. Google 스팸 정책의 "숨겨진 텍스트 및 링크"에 걸리면
 *    순위 하락이 아니라 색인 삭제(수동 조치)로 간다.
 * 2) 얇은 글 양산 금지. doorway pages 로 분류되면 같은 결과다.
 *    한 편은 최소 4~5개 섹션, 실제로 읽고 따라 할 수 있는 분량으로 쓴다.
 * 3) 숫자는 지어내지 않는다. 수수료·정산 같은 수치는 CHANNEL_ONBOARDING_GUIDES 의
 *    실데이터를 참조하거나, 확정적으로 못 쓰면 범위·조건을 명시한다.
 * 4) slug 는 ASCII 만. 이 레포는 Google Drive 경로라 한글 디렉터리가 EPERM 으로 잠긴다.
 */

export interface ArticleSection {
  heading: string;
  /** 문단들 */
  body: string[];
  /** 선택: 목록 */
  list?: string[];
  /** 선택: 표 (첫 행이 헤더) */
  table?: { headers: string[]; rows: string[][] };
  /** 선택: 강조 박스 */
  callout?: { kind: 'tip' | 'warn'; text: string };
}

export interface GuideArticle {
  slug: string;
  title: string;
  /** 메타 설명 (155자 이내 권장) */
  description: string;
  keywords: string[];
  /** 문서 상단 리드 문단 */
  lead: string;
  /** 발행/수정일 (ISO) — Article 구조화 데이터에 쓰인다 */
  published: string;
  updated: string;
  sections: ArticleSection[];
  /** FAQPage 구조화 데이터로 나갈 Q&A */
  faq?: { q: string; a: string }[];
  /** 관련 문서 slug (내부 링크) */
  related?: string[];
}

