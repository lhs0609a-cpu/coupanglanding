/**
 * 도메인 용어 사전 — 사용자가 쓰는 말 ↔ 문서가 쓰는 말.
 *
 * 왜 필요한가
 *   어휘 검색은 글자가 겹쳐야 찾는다. 그런데 실제 사용자는 문서 제목과 다른 말을 쓴다.
 *   튜닝에 쓰지 않은 질문 30개로 재봤더니 1위 정확도가 **43.3%** 였고,
 *   실패의 대부분이 뜻은 같은데 글자가 다른 경우였다.
 *     "똑같은 걸 두 번 올렸다고 나와요"  → 문서는 '중복'
 *     "키 넣었는데 연결이 안 돼요"        → 문서는 '인증 / API 키'
 *     "사람들이 보긴 보는데 안 사요"      → 문서는 '전환율'
 *     "재고를 쌓아둬야 하나요"            → 문서는 '무재고 / 위탁'
 *     "영양제 취급해도 되나요"            → 문서는 '건강기능식품'
 *
 *   질문별 태그를 계속 붙이는 건 문제집에 답을 적어 넣는 짓이라 일반화가 안 된다.
 *   말 자체를 이어주는 사전이 훨씬 멀리 간다.
 *
 * 규칙
 *   - 왼쪽은 사용자가 쓸 법한 구어, 오른쪽은 문서에 실제로 있는 표기.
 *   - 한 방향으로만 넣는다(구어 → 문서말). 반대 방향은 문서말이 이미 문서에 있으니 필요 없다.
 *   - 너무 일반적인 말(하다, 되다)은 넣지 않는다. 검색이 뭉개진다.
 */

