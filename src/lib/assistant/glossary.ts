/**
 * 질의에 등장한 구어를 문서말로 넓힌다.
 * 원래 단어는 그대로 두고 **추가**만 한다 — 원문 매칭을 잃으면 안 된다.
 */
export function expandSynonyms(query: string): string[] {
  const flat = query.toLowerCase().replace(/\s+/g, '');
  const out = new Set<string>();
  for (const [surface, canonicals] of Object.entries(SYNONYMS)) {
    if (flat.includes(surface)) {
      for (const c of canonicals) out.add(c);
    }
  }
  return [...out];
}
