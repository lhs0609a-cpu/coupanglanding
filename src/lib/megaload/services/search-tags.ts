/** 사전이 안 걸릴 때만 쓰는 최후의 조합어 — 몇 칸만 메운다(같은 핵심어 반복은 노출을 안 늘린다). */
const PAD_COMBO = ['대용량', '세트', '선물용', '가정용', '업소용', '묶음'];

function padCandidates(categoryPath: string): string[] {
  const path = String(categoryPath || '');
  // ⚠️ 핵심어는 **카테고리에서만** 뽑는다. 상품명에서 뽑으면 타사 브랜드가 그대로 실린다 —
  //    실측 2026-09-01: "썬키스트 오렌지 대용량…" 에서 "대용량썬키스트" 가 만들어졌다.
  //    쿠팡은 태그에 타사 브랜드명을 금지한다(계정 위험). 카테고리에는 브랜드가 없다.
  const parts = path.split(/[>/]/).map((x) => x.trim()).filter(Boolean);
  const leaf = (parts[parts.length - 1] || '').replace(/\s+/g, '');
  const out: string[] = [];
  // ① 도메인 어휘 — 유형이 섞여 있어 도달하는 검색어 집합이 실제로 넓어진다.
  //    ⚠️ **가장 먼저 걸리는 사전 하나만** 쓴다(배열이 구체적→일반 순이다). 여러 개를 합치면
  //       엉뚱한 어휘가 섞인다 — 실측: "가전>청소기" 가 생활/청소 사전에도 걸려 "리필" 이
  //       태그로 나왔다. 청소기는 리필 상품이 아니다. 어긋난 태그는 계정 위험이다.
  const hit = DOMAIN_VOCAB.find((d) => d.re.test(path));
  if (hit) out.push(...hit.words);
  // ② 최후의 조합어 — 사전만으로 못 채운 나머지. 순서상 뒤라 사전이 있으면 거의 안 쓰인다.
  if (leaf.length >= 2) {
    for (const m of PAD_COMBO) { out.push(`${m}${leaf}`); out.push(`${leaf}${m}`); }
  }
  return out;
}

/**
 * 아는 어휘를 부분문자열로 지운 뒤, 남는 한글 덩어리(2자 이상)가 있으면 낯선 고유명으로 본다.
 *   한국어 합성 검색어를 토큰 단위로 못 가르기 때문에 필요한 방식이다.
 * @param s 후보 검색어
 * @param known 이 상품이 아는 어휘(긴 것부터 정렬돼 있어야 한다)
 */
function hasUnknownProperNoun(s: string, known: string[]): boolean {
  let rest = s.toLowerCase().replace(/\s+/g, '');
  for (const w of known) {
    if (!w) continue;
    rest = rest.split(w).join(' ');           // 아는 어휘 제거
    if (!rest.replace(/\s+/g, '')) return false;
  }
  // 숫자·단위·영문은 고유명으로 보지 않는다(150ml, 2봉, XL 등).
  rest = rest.replace(/[0-9a-z.%]+/g, ' ');
  return /[가-힣]{2,}/.test(rest);
}

